# 6. THE ARS MAGNA ENGINE
# ═══════════════════════════════════════════════════════════════════════════

class ArsMagna:
    """
    Llull's Ars Magna combinatorial generator.
    
    Fully functional paper computer in Python.
    
    Takes a subject, runs it through all 84 valid triples
    × 18 questions = 1,512 generated propositions.
    
    Each proposition is an output of the Art — a statement
    about the subject derived from first principles.
    """
    
    def __init__(self):
        self.principles = PRINCIPLES
        self.relative = RELATIVE_PRINCIPLES
        self.triples = CANONICAL_TRIPLES  # 84 valid combinations
        self.questions = LLULL_QUESTIONS   # 18 inquiries
        self.wheel = LetterWheel()
    
    # ── Principle Resolution ───────────────────────────────────────────
    
    def resolve_triple(self, triple):
        """
        Resolve a letter-triple into its meanings.
        
        (B, C, D) → "Goodness-Greatness-Eternity"
        """
        names = []
        for letter in triple:
            if letter in self.principles:
                p = self.principles[letter]
                names.append(f"{p['english']} ({p['name']})")
            else:
                names.append(letter)
        return " — ".join(names)
    
    def triple_meaning(self, triple):
        """
        Generate the semantic meaning of a triple.
        
        Llull: combining two principles produces a third.
        B+C → the goodness of greatness, etc.
        """
        if len(triple) < 2:
            return self.resolve_triple(triple)
        
        l1 = self.principles.get(triple[0], {})
        l2 = self.principles.get(triple[1], {})
        l3 = self.principles.get(triple[2], {})
        
        meaning = f"{l1.get('english','?')} expressed through {l2.get('english','?')}"
        if l3:
            meaning += f" toward {l3.get('english','?')}"
        
        return meaning
    
    # ── Combination Generation ─────────────────────────────────────────
    
    def all_triples(self):
        """Yield all 84 valid triples with their resolved meanings."""
        for triple in self.triples:
            yield {
                "triple": triple,
                "as_string": "".join(triple),
                "resolution": self.resolve_triple(triple),
                "meaning": self.triple_meaning(triple),
            }
    
    def generate_by_rotation(self, max_rotations=9):
        """
        Generate triples by physically rotating the wheel.
        
        Like Llull's actual paper computer: rotate the wheel
        one position at a time, reading off the valid combinations
        at each position.
        """
        all_generated = []
        for rot in range(max_rotations):
            self.wheel.rotation = rot
            order = self.wheel.current_order()
            
            # At this rotation, generate triples from the current ordering
            rotation_triples = []
            for i in range(9):
                for j in range(i, 9):
                    for k in range(j, 9):
                        if i == j == k:
                            continue
                        triple = self.wheel.triple_at(i, j, k)
                        rotation_triples.append({
                            "rotation": rot,
                            "positions": (i, j, k),
                            "triple": triple,
                            "as_string": "".join(triple),
                            "resolution": self.resolve_triple(triple),
                        })
            
            all_generated.append({
                "rotation": rot,
                "wheel_order": order,
                "triples": rotation_triples,
                "count": len(rotation_triples),
            })
        
        return all_generated
    
    # ── The Question Engine ────────────────────────────────────────────
    
    def apply_to_subject(self, subject, top_n=None):
        """
        Apply ALL 84 triples × 18 questions to a subject.
        
        Returns a ranked list of (triple, question, meaning) where
        the combination produces a meaningful proposition.
        
        This is Llull's actual method: for any subject you want
        to understand, you run it through the full combinatorial grid.
        """
        results = []
        
        for triple_info in self.all_triples():
            triple_str = triple_info["as_string"]
            resolution = triple_info["resolution"]
            meaning = triple_info["meaning"]
            
            for q in self.questions:
                question = q.format(triple=triple_str, subject=subject)
                proposition = f"{resolution} — {meaning}"
                
                results.append({
                    "triple": triple_str,
                    "question": question,
                    "proposition": proposition,
                    "resolution": resolution,
                })
        
        # Score: how well does this triple resonate with the subject?
        # Simple bag-of-words overlap + structural match
        scored = []
        for r in results:
            subj_lower = subject.lower()
            resolution_lower = r["resolution"].lower()
            
            # Direct word overlap
            subj_words = set(subj_lower.split())
            res_words = set(resolution_lower.split())
            word_overlap = len(subj_words & res_words)
            
            # Letter overlap with subject
            triple_letters = set(r["triple"].lower())
            subj_letters = set(subj_lower)
            letter_overlap = len(triple_letters & subj_letters) / max(len(triple_letters), 1)
            
            # Composite score
            score = word_overlap * 2 + letter_overlap * 3
            scored.append((score, r))
        
        scored.sort(key=lambda x: x[0], reverse=True)
        
        if top_n:
            scored = scored[:top_n]
        
        return [item for score, item in scored]
    
    # ── Combinatorial Search (Llull as problem solver) ─────────────────
    
    def solve(self, subject, max_generations=3):
        """
        Use Ars Magna as a problem solver.
        
        Generation 1: Apply subject to all triples → propositions
        Generation 2: Use strongest propositions as new subjects
        Generation 3: Refine further
        
        Each generation narrows the combinatorial space toward
        the most meaningful permutation.
        """
        results = {}
        
        gen1 = self.apply_to_subject(subject, top_n=20)
        results["generation_1"] = gen1
        
        if max_generations >= 2 and gen1:
            # Take the best proposition as a new subject
            best_triple = gen1[0]["triple"]
            gen2_subject = f"{subject} {best_triple}"
            gen2 = self.apply_to_subject(gen2_subject, top_n=10)
            results["generation_2"] = gen2
            
            if max_generations >= 3 and gen2:
                best_triple_2 = gen2[0]["triple"]
                gen3_subject = f"{gen2_subject} {best_triple_2}"
                gen3 = self.apply_to_subject(gen3_subject, top_n=5)
                results["generation_3"] = gen3
        
        return results

    # ── Wire into 72-band Framework ────────────────────────────────────

    def lullian_72_vector(self, subject):
        """
        Decompose a subject through Llull's triples into a 72-band vector.
        
        Each triple maps to a band via its letter positions.
        The density of questions that resolve positively for this
        subject determines the band energy.
        
        72 bands = 84 triples, but triples can overlap bands.
        We map: triple letter-sum → band index.
        """
        bands = [0.0] * 72
        
        # Generate all propositions for the subject
        propositions = self.apply_to_subject(subject)
        
        for prop in propositions:
            triple = prop["triple"]
            # Convert letters to numeric values (B=1, C=2, ..., K=9)
            letter_vals = [ord(l) - ord('B') + 1 for l in triple if l in "BCDEFGHIK"]
            if letter_vals:
                # Triple sum → band position
                triple_sum = sum(letter_vals)
                band = (triple_sum + len(prop["question"])) % 72
                bands[band] += 1.0
        
        # Normalize
        total = sum(bands)
        if total > 0:
            bands = [b / total for b in bands]
        
        return bands

    # ── Report ─────────────────────────────────────────────────────────

    def report_subject(self, subject, top_n=10):
        """Pretty-print the Ars Magna analysis of a subject."""
        props = self.apply_to_subject(subject, top_n=top_n)
        bands = self.lullian_72_vector(subject)
        dominant_band = bands.index(max(bands))
        
        lines = []
        lines.append(f"═" * 68)
        lines.append(f" ARS MAGNA — COMBINATORIAL ANALYSIS OF '{subject.upper()}'")
        lines.append(f"═" * 68)
        lines.append(f"  84 triples × 18 questions = 1,512 propositions generated")
        lines.append(f"  Dominant 72-band: {dominant_band + 1}")
        lines.append(f"")
        lines.append(f"  TOP PROPOSITIONS (ranked by resonance):")
        lines.append(f"  {'─' * 64}")
        
        for i, p in enumerate(props[:top_n], 1):
            lines.append(f"  {i:2d}. [{p['triple']}] {p['resolution']}")
            lines.append(f"      Q: {p['question']}")
            lines.append(f"      → {p['proposition']}")
            lines.append(f"")
        
        # Band vector summary
        lines.append(f"  BAND VECTOR (top 6 bands):")
        band_indices = sorted(range(72), key=lambda i: bands[i], reverse=True)
        for idx in band_indices[:6]:
            lines.append(f"    Band {idx+1:2d}: {bands[idx]:.4f}")
        
        # Solve pathway
        solved = self.solve(subject, max_generations=3)
        lines.append(f"")
        lines.append(f"  SOLVE PATHWAY (3 generations):")
        for gen_name, gen_data in solved.items():
            if gen_data:
                best = gen_data[0]
                lines.append(f"    {gen_name}: [{best['triple']}] {best['resolution']}")
        
        lines.append(f"═" * 68)
        return "\n".join(lines)

    def report_wheel(self, rotations=9):
        """Show the letter-wheel in action at each rotation."""
        lines = []
        lines.append(f"═" * 68)
        lines.append(f" ARS MAGNA — LETTER WHEEL ROTATION")
        lines.append(f"═" * 68)
        
        wheel_states = self.generate_by_rotation(rotations)
        for state in wheel_states:
            r = state["rotation"]
            order = " ".join(state["wheel_order"])
            count = state["count"]
            lines.append(f"  Rotation {r}: [{order}] → {count} triples")
            
            # Show first 3 triples for each rotation
            for t in state["triples"][:3]:
                meaning = self.resolve_triple(t["triple"])
                lines.append(f"    {t['as_string']} = {meaning}")
            if count > 3:
                lines.append(f"    ... and {count - 3} more")
        
        lines.append(f"═" * 68)
        return "\n".join(lines)

    def report_all_triples(self):
        """Print all 84 valid triples with meanings."""
        lines = [f"═" * 52, f" 84 VALID TRIPLES (LLULL'S ARS MAGNA)", f"═" * 52]
        for i, t in enumerate(self.all_triples(), 1):
            lines.append(f"  {i:2d}. {t['as_string']}  =  {t['resolution']}")
        lines.append(f"═" * 52)
        return "\n".join(lines)


