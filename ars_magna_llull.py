# The 84 canonical triples (Llull's valid combinations of B-K)
# Generated by: first letter fixed, second letter >= first, third unrestricted
# But NOT all triples — only those that produce meaningful relations.

def generate_canonical_triples():
    """
    Generate the 84 valid Llullian triples.
    
    Rule: For each fixed first letter, cycle the second letter
    through positions >= first, and third through all remaining letters.
    
    The result is 84 triples that form the COMPLETE set of valid
    combinatorial relations.
    """
    letters = list(PRINCIPLES.keys())
    triples = []
    
    for i, l1 in enumerate(letters):
        for j, l2 in enumerate(letters):
            if j < i:
                continue
            for k, l3 in enumerate(letters):
                if k < j:
                    continue
                # Skip self-only triples (all same letter)
                if l1 == l2 == l3 and len(set([l1, l2, l3])) == 1:
                    continue
                triples.append((l1, l2, l3))
    
    return triples

CANONICAL_TRIPLES = generate_canonical_triples()

# ═══════════════════════════════════════════════════════════════════════════
# 4. THE LETTER WHEEL
# ═══════════════════════════════════════════════════════════════════════════

class LetterWheel:
    """
    Llull's combinatorial letter-wheel.
    
    A circle with 9 sectors (B through K) that rotates.
    When combined with another wheel, every valid combination
    can be generated by rotating the wheels.
    
    Attributes:
        letters: Ordered list of 9 letters
        rotation: Current rotation offset (0-8)
    """
    
    def __init__(self, letters=None, rotation=0):
        self.letters = letters or list(PRINCIPLES.keys())
        self.rotation = rotation
    
    def rotate(self, steps=1):
        """Rotate the wheel by N steps."""
        self.rotation = (self.rotation + steps) % 9
        return self
    
    def at_position(self, pos):
        """Get the letter at a given position (0-8), accounting for rotation."""
        idx = (pos + self.rotation) % 9
        return self.letters[idx]
    
    def current_order(self):
        """Return the current order of letters."""
        return [self.letters[(i + self.rotation) % 9] for i in range(9)]
    
    def triple_at(self, outer_pos, middle_pos, inner_pos):
        """
        Get a triple (B, C, D) from three concentric wheels at different rotations.
        
        Like Llull's actual paper device: three concentric circles,
        each with 9 sectors. Rotate independently, read the triple
        where they align.
        """
        b = self.at_position(outer_pos)
        c = self.at_position(middle_pos)
        d = self.at_position(inner_pos)
        return (b, c, d)


